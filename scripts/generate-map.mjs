// Generates src/data/map.generated.ts — a dot-matrix of the contiguous US plus
// projected hub coordinates. Run with `npm run gen:map`; output is committed so
// no geo libraries ship to the browser.
import { writeFileSync } from 'node:fs'
import { readFile } from 'node:fs/promises'
import { geoAlbers, geoContains } from 'd3-geo'
import { merge } from 'topojson-client'

const topo = JSON.parse(await readFile(new URL('../node_modules/us-atlas/states-10m.json', import.meta.url)))
const excluded = new Set(['02', '15', '60', '66', '69', '72', '78'])
const geoms = topo.objects.states.geometries.filter((g) => !excluded.has(g.id))
const lower48 = merge(topo, geoms)

const W = 1000
const H = 620
const projection = geoAlbers().fitExtent([[24, 24], [W - 24, H - 24]], lower48)

const STEP = 10
const segs = []
for (let y = STEP / 2; y < H; y += STEP) {
  for (let x = STEP / 2; x < W; x += STEP) {
    const ll = projection.invert([x, y])
    if (ll && geoContains(lower48, ll)) segs.push(`M${x} ${y}h0`)
  }
}

const hubs = [
  ['SEA', 'Seattle, WA', 47.61, -122.33],
  ['LAX', 'Los Angeles, CA', 34.05, -118.24],
  ['PHX', 'Phoenix, AZ', 33.45, -112.07],
  ['SLC', 'Salt Lake City, UT', 40.76, -111.89],
  ['DEN', 'Denver, CO', 39.74, -104.99],
  ['DAL', 'Dallas, TX', 32.78, -96.8],
  ['HOU', 'Houston, TX', 29.76, -95.37],
  ['KC', 'Kansas City, MO', 39.1, -94.58],
  ['CHI', 'Chicago, IL', 41.88, -87.63],
  ['MEM', 'Memphis, TN', 35.15, -90.05],
  ['ATL', 'Atlanta, GA', 33.75, -84.39],
  ['CLT', 'Charlotte, NC', 35.23, -80.84],
  ['JAX', 'Jacksonville, FL', 30.33, -81.66],
  ['CMH', 'Columbus, OH', 39.96, -83.0],
  ['NYC', 'New York, NY', 40.71, -74.01],
].map(([code, name, lat, lon]) => {
  const [x, y] = projection([lon, lat])
  return { code, name, lat, lon, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 }
})

const out = `// AUTO-GENERATED by scripts/generate-map.mjs — do not edit by hand.
import type { Hub } from './types'

export const MAP_WIDTH = ${W}
export const MAP_HEIGHT = ${H}
export const MAP_DOTS = '${segs.join('')}'

export const HUBS: Hub[] = ${JSON.stringify(hubs, null, 2)}
`
writeFileSync(new URL('../src/data/map.generated.ts', import.meta.url), out)
console.log(`dots: ${segs.length}, bytes: ${out.length}`)
